"""Exercise real uninstall with filesystem effects confined to a temp tree."""

import contextlib
import io
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest.mock import patch

from test_release import load_program


class QuotaCleanupTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name).resolve()
        self.roots = (self.root / "persistent", self.root / "runtime")
        self.cli = load_program("BIN")
        self.commands = []
        self.quotas = [root / "resource-balancer-cpu.service.d" / "50-CPUQuota.conf" for root in self.roots]
        for path in self.quotas:
            path.parent.mkdir(parents=True)
            path.write_bytes(b"# Generated by systemctl set-property\n[Service]\nCPUQuota=125%\n")
        for name in ("/usr/local/bin/resource-balancer", "/usr/local/lib/resource-balancer/cpu.py",
                     "/etc/resource-balancer.conf", "/var/lib/resource-balancer/metrics.csv"):
            path = self.root / name.lstrip("/")
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(b"keep unless removed\n")

    def run_command(self, command, **kwargs):
        self.commands.append(command)
        if command[0] == "systemctl":
            output = ("LoadState=loaded\nActiveState=inactive\n"
                      if "--property=LoadState,ActiveState" in command else "inactive\n")
            return subprocess.CompletedProcess(command, 0, stdout=output)
        self.assertEqual(command[0], "rm")
        for value in command[2:]:
            target = (self.root / value.lstrip("/")).resolve()
            self.assertIn(self.root, target.parents)
            if target.is_dir():
                shutil.rmtree(target)
            elif target.exists():
                target.unlink()
        return subprocess.CompletedProcess(command, 0)

    @contextlib.contextmanager
    def isolated(self):
        with patch.object(self.cli, "SYSTEMD_CONTROL_DIRS", tuple(map(str, self.roots))), \
             patch.object(self.cli.os, "geteuid", return_value=0, create=True), \
             patch.object(self.cli.subprocess, "run", side_effect=self.run_command), \
             contextlib.redirect_stdout(io.StringIO()) as output:
            yield output

    def test_normal_uninstall_removes_only_owned_quota(self):
        unrelated = self.quotas[0].parent / "90-admin.conf"
        unrelated.write_bytes(b"[Service]\nCPUQuota=75%\nCPUWeight=10\n")
        with self.isolated():
            self.cli.uninstall([])
        self.assertTrue(all(not path.exists() for path in self.quotas))
        self.assertEqual(unrelated.read_bytes(), b"[Service]\nCPUQuota=75%\nCPUWeight=10\n")
        self.assertTrue((self.root / "etc/resource-balancer.conf").exists())
        self.assertTrue((self.root / "var/lib/resource-balancer/metrics.csv").exists())

    def test_purge_removes_both_quota_layers_and_project_data(self):
        with self.isolated() as output:
            self.cli.uninstall(["--purge"])
        self.assertTrue(all(not path.exists() for path in self.quotas))
        self.assertFalse((self.root / "etc/resource-balancer.conf").exists())
        self.assertFalse((self.root / "var/lib/resource-balancer").exists())
        self.assertIn("completely removed", output.getvalue())

    def test_mixed_file_preserves_unrelated_directives_and_mode(self):
        contents = b"# Admin note\n[Service]\nCPUQuota=25%\nCPUWeight=7\n[Unit]\nDescription=Custom\n"
        self.quotas[0].write_bytes(contents)
        os.chmod(self.quotas[0], 0o640)
        with self.isolated():
            self.cli.uninstall(["--purge"])
        self.assertEqual(self.quotas[0].read_bytes(), contents.replace(b"CPUQuota=25%\n", b""))
        if os.name == "posix":
            self.assertEqual(self.quotas[0].stat().st_mode & 0o777, 0o640)

    def test_quota_delete_failure_keeps_cli_and_can_retry(self):
        original_unlink = Path.unlink
        failed = False

        def unlink(path, *args, **kwargs):
            nonlocal failed
            if path == self.quotas[1] and not failed:
                failed = True
                raise PermissionError("injected quota removal failure")
            return original_unlink(path, *args, **kwargs)

        with self.isolated() as output, patch.object(Path, "unlink", unlink):
            with self.assertRaises(PermissionError):
                self.cli.uninstall(["--purge"])
            self.assertTrue((self.root / "usr/local/bin/resource-balancer").exists())
            self.assertNotIn("completely removed", output.getvalue())
            self.cli.uninstall(["--purge"])
        self.assertTrue(all(not path.exists() for path in self.quotas))
        self.assertFalse((self.root / "usr/local/bin/resource-balancer").exists())

    def test_quota_cleanup_precedes_final_manager_reload(self):
        original_run = self.run_command
        reload_checks = []

        def run(command, **kwargs):
            if command[:2] == ["systemctl", "daemon-reload"]:
                reload_checks.append(all(not path.exists() for path in self.quotas))
            return original_run(command, **kwargs)

        with self.isolated(), patch.object(self.cli.subprocess, "run", side_effect=run):
            self.cli.uninstall([])
        self.assertEqual(reload_checks[0], False)
        self.assertTrue(reload_checks[-1])

    def test_multiline_quota_is_preserved_and_uninstall_fails_safely(self):
        contents = b"[Service]\nCPUQuota=\\\n25%\nCPUWeight=7\n"
        self.quotas[0].write_bytes(contents)
        with self.isolated() as output:
            with self.assertRaises(RuntimeError):
                self.cli.uninstall(["--purge"])
        self.assertEqual(self.quotas[0].read_bytes(), contents)
        self.assertTrue((self.root / "usr/local/bin/resource-balancer").exists())
        self.assertNotIn("completely removed", output.getvalue())

    def test_mixed_file_write_failure_keeps_original_and_allows_retry(self):
        original = b"[Service]\nCPUQuota=25%\nCPUWeight=7\n"
        self.quotas[0].write_bytes(original)
        original_write = self.cli.atomic_write
        failed = False

        def write(path, data, mode=0o600):
            nonlocal failed
            if path == str(self.quotas[0]) and not failed:
                failed = True
                raise OSError("injected write failure")
            return original_write(path, data, mode)

        with self.isolated() as output, patch.object(self.cli, "atomic_write", side_effect=write):
            with self.assertRaises(OSError):
                self.cli.uninstall([])
            self.assertEqual(self.quotas[0].read_bytes(), original)
            self.assertTrue((self.root / "usr/local/bin/resource-balancer").exists())
            self.assertNotIn("program removed", output.getvalue())
            self.cli.uninstall([])
        self.assertEqual(self.quotas[0].read_bytes(), original.replace(b"CPUQuota=25%\n", b""))

    def test_quota_symlink_does_not_modify_its_target(self):
        target = self.root / "administrator.conf"
        target.write_bytes(b"[Service]\nCPUQuota=50%\n")
        self.quotas[0].unlink()
        try:
            self.quotas[0].symlink_to(target)
        except OSError as error:
            self.skipTest(f"symlink unavailable: {error}")
        with self.isolated() as output:
            with self.assertRaises(RuntimeError):
                self.cli.uninstall(["--purge"])
        self.assertEqual(target.read_bytes(), b"[Service]\nCPUQuota=50%\n")
        self.assertTrue(self.quotas[0].is_symlink())
        self.assertTrue((self.root / "usr/local/bin/resource-balancer").exists())
        self.assertNotIn("completely removed", output.getvalue())


if __name__ == "__main__":
    unittest.main()
